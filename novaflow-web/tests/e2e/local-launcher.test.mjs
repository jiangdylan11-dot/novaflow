import assert from 'node:assert/strict';
import { createLauncherFixture } from '../helpers/launcher-fixture.mjs';
let checks = 0;
const equal = (a, b) => { assert.equal(a, b); checks++; };
const f = await createLauncherFixture();
equal(f.windows.length, 1);
equal(f.windows[0].options.minWidth >= 620, true);
equal((await f.call('start')).needsLicense, true);
equal(f.instances.length, 0);
equal((await f.call('license')).state.machineId, 'TEST-MACHINE-ONLY');
f.config.registrationCode = 'bad-code';
equal((await f.call('share')).ok, false);
equal(f.instances[0].stopped, true);
await f.call('setConfig', { registrationCode: 'test-node' });
equal((await f.call('share')).ok, true);
equal(f.instances.length, 2);
equal(f.instances[1].getState().localRunning, false);
equal(f.config.registrationCode, '');
equal(f.opened.length, 0);
equal((await f.call('start')).needsLicense, true);
equal(f.instances[1].getState().sharing, true);
equal((await f.handlers.get('worker:licenseImportText')({ sender: {} }, 'test-only-license')).ok, false);
equal((await f.call('licenseImportText', 'invalid')).ok, false);
equal((await f.call('licenseImportFile')).canceled, true);
f.fileCanceled = false;
equal((await f.call('licenseImportFile')).ok, true);
equal(f.instances[1].getState().localRunning, false);
equal(f.opened.length, 0); // Authorization alone does not launch anything.
f.localFailure = true;
equal((await f.call('start')).ok, false);
equal(f.instances[1].getState().sharing, true);
f.localFailure = false;
const results = await Promise.all([f.call('start'), f.call('start')]);
equal(results.every(r => r.ok), true);
equal(f.opened.length, 1);
equal(results[0].state.localRunning && results[0].state.sharing, true);
equal((await f.call('stop')).state.sharing, true);
equal(f.instances[1].getState().localRunning, false);
await f.call('start');
equal((await f.call('unshare')).state.localRunning, true);
equal(f.instances[1].getState().sharing, false);
await f.call('stop');
f.licenseState.locked = true;
equal((await f.call('start')).needsLicense, true);
equal((await f.call('share')).ok, true);
await f.call('openWebsite');
equal(f.opened.at(-1), 'https://novaflow.jiangdylan11.workers.dev/');
equal(f.windows.length, 1);
equal((await f.call('openLocal')).ok, false);
f.licenseState.locked = false;
await f.call('start');
const count = f.instances.length;
equal((await f.call('openLocal')).ok, true);
equal(f.instances.length, count);
equal(f.opened.at(-1), f.instances.at(-1).openUrl);
equal((await f.call('getState')).operations.local.percent, 100);
await f.call('share');
let prevented = false;
f.windows[0].emit('close', { preventDefault() { prevented = true; } });
equal(prevented, true);
equal(f.windows[0].hidden, true);
equal((await f.call('getState')).localRunning, true);
equal((await f.call('getState')).sharing, true);
f.app.emit('second-instance');
equal(f.windows[0].hidden, false);
equal(f.windows[0].focused, true);
f.windows[0].emit('close', { preventDefault() {} });
f.tray.emit('click');
equal(f.windows[0].hidden, false);
equal(f.tray.tooltip, 'NovaFlow 本地助手');
await f.tray.menu.find(item => item.label === '退出本地助手').click();
equal(f.instances.at(-1).stopped, true);
equal(f.app.quitCalled, true);
prevented = false;
f.windows[0].emit('close', { preventDefault() { prevented = true; } });
equal(prevented, false);
console.log(checks + ' passed, 0 failed: independent launcher controls and inline authorization');
