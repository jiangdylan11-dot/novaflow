// Extract only existing pure business functions. Renderer remains the source of
// truth; --check fails if generated copies drift. Refreshing an existing file
// requires --refresh and its exact --expect-h3 / --expect-art target SHA-256.
// This does not wire a route.
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {dirname,resolve} from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const read=async path=>(await readFile(resolve(root,path),'utf8')).replace(/\r\n/g,'\n');
const sha=s=>createHash('sha256').update(s,'utf8').digest('hex');
function once(source,marker) {const start=source.indexOf(marker);if(start<0||source.indexOf(marker,start+marker.length)>=0)throw Error(`source marker not unique: ${marker}`);return start;}
const h3=await read('renderer/ai-sequence-minimax-h3-reverse.workflow.js');
const h3Marker="})(typeof globalThis !== 'undefined' ? globalThis : this, function (promptWorkflow) {";
const h3Start=once(h3,h3Marker)+h3Marker.length,h3End=h3.lastIndexOf('\n})');
if(h3End<=h3Start || h3.slice(h3End).trim()!=='})')throw Error('unexpected H3 reverse wrapper');
const art=await read('renderer/novaflow-smart-ai.js');
const sectionsStart=once(art,'  const ORDINARY_ART_PROMPT_SECTIONS ='),sectionsEnd=once(art,'  const MINIMAX_H3_MODE_VALUES =');
const start=once(art,'  const SMART_AI_PROMPT_PRESERVATION_STOPWORDS ='),end=once(art,'  function smartAiPromptPreservationError(');
const fusionStart=once(art,'  function prepareStaticArtReverseFusion('),fusionEnd=once(art,'  async function fuseStaticArtReversePrompt(');
if(!(sectionsStart<sectionsEnd&&sectionsEnd<start&&start<end&&end<fusionStart&&fusionStart<fusionEnd))throw Error('unexpected static fusion source layout');
const files=[
  ['packages/shared/src/xiaotao-h3-reverse-factory-v3.mjs',`// GENERATED by tools/sync-legacy-ai-server-v3.mjs; source sha256 ${sha(h3)}.\nexport function createH3ReverseWorkflow(promptWorkflow) {${h3.slice(h3Start,h3End)}\n}\n`],
  ['packages/shared/src/xiaotao-static-fusion-v3.mjs',`// GENERATED by tools/sync-legacy-ai-server-v3.mjs; source sha256 ${sha(art)}.\n${art.slice(sectionsStart,sectionsEnd)}\n${art.slice(start,end)}\n${art.slice(fusionStart,fusionEnd)}\nexport {prepareStaticArtReverseFusion,validateSmartAiArtPromptPreservation,validateSmartAiStructuredArtPrompt};\n`]
];
for(const [index,[path,content]] of files.entries()){
 const file=resolve(root,path);
 if(process.argv.includes('--check')){let actual='';try{actual=(await readFile(file,'utf8')).replace(/\r\n/g,'\n');}catch{}if(actual!==content)throw Error(`generated source differs: ${path}`);}
 else if(process.argv.includes('--refresh')){
  const flag=index===0?'--expect-h3=':'--expect-art=';
  const expected=process.argv.find(x=>x.startsWith(flag))?.slice(flag.length);
  const actual=await readFile(file,'utf8');
  if(!/^[a-f0-9]{64}$/i.test(expected||'') || sha(actual)!==expected.toLowerCase())throw Error(`target SHA required or changed: ${path}`);
  await writeFile(file,content,'utf8');
 } else await writeFile(file,content,{flag:'wx'});
 console.log(`${process.argv.includes('--check')?'verified':'generated'} ${path}`);
}
