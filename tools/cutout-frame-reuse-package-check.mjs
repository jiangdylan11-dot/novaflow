import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const root=path.resolve(import.meta.dirname,'..'),out=path.join(root,'docs/cutout-frame-reuse-20260914');
const installer=path.join(root,'particle-editor-desktop/dist/NovaFlow Setup 2.3.214 - 播放缓存复用与连续抠图修复.exe');
const target=path.join(out,'nsis');
const seven=path.join(root,'particle-editor-desktop/node_modules/7zip-bin/win/x64/7za.exe');
const extracted=spawnSync(seven,['x','-y',installer,'-o'+target],{encoding:'utf8',windowsHide:true});
assert.equal(extracted.status,0,extracted.stderr);
const previous=JSON.parse(fs.readFileSync(path.join(root,'docs/history-storage-15-20260914/package-validation.json')));
const hash=file=>createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const files=previous.files.map(({file})=>{
 const source=file.startsWith('renderer/')?path.join(root,'particle-editor',file.slice(9)):path.join(root,'particle-editor-desktop',file);
 const shipped=path.join(target,'resources/app',file);
 assert.equal(hash(source),hash(shipped),file);
 return {file,sha256:hash(shipped),match:true};
});
const shippedBundle=path.join(target,'resources/app/renderer/assets/index-BbIa-2NM.js');
const tests=['prompt-history-display-limit.test.mjs','cutout-next-source.test.cjs'].map(file=>path.join(root,'particle-editor-desktop/tests',file));
const test=spawnSync(process.execPath,['--test',...tests],{encoding:'utf8',windowsHide:true,env:{...process.env,NOVAFLOW_HISTORY_TEST_BUNDLE:shippedBundle,NOVAFLOW_CUTOUT_TEST_BUNDLE:shippedBundle}});
assert.equal(test.status,0,test.stdout+test.stderr);
const bundle=fs.readFileSync(shippedBundle,'utf8');
assert(bundle.includes('data-novaflow-cutout-error')&&bundle.includes('nfFinalFrames'));
const report={installer,bytes:fs.statSync(installer).size,sha256:hash(installer),files,packagedHistoryAndNextSourceTests:'PASS'};
fs.writeFileSync(path.join(out,'package-validation.json'),JSON.stringify(report,null,2));
fs.writeFileSync(path.join(out,'packaged-tests.txt'),test.stdout);
console.log(JSON.stringify({installer,bytes:report.bytes,sha256:report.sha256,files:files.length,packagedTests:'PASS'}));
