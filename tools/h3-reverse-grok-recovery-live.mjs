import fs from 'node:fs';
import vm from 'node:vm';
import {createRequire} from 'node:module';
import {buildGrokImageReverseRequest,grokResponsesPublicResult,callGrokResponseWithVisualRetry} from '../supabase/functions/novaflow-backend/smart-ai-grok.workflow.mjs';
const require=createRequire(import.meta.url);
const config=require('../particle-editor-desktop/license-admin-gui/admin-data.js').readAdminGrokEnv();
const mode=process.argv.find(arg=>arg.startsWith('--mode='))?.slice(7);
const out=new URL(mode?'../docs/h3-mode-matrix-validation/':'../docs/h3-recovery-validation/',import.meta.url);
const prefix=mode?`grok-${mode}-reverse`:'grok-reverse';
const payload=JSON.parse(fs.readFileSync(new URL(mode?`local-${mode}-reverse-request.json`:'local-fl2v-reverse-request.json',out),'utf8'));
const built=buildGrokImageReverseRequest(payload,config.model);
let calls=0; const started=Date.now();
const result=await callGrokResponseWithVisualRetry(built.body,built.inputMeta,built.resultOptions,async body=>{
  calls++;
  const response=await fetch(config.baseUrl.replace(/\/$/,'')+'/responses',{method:'POST',headers:{Authorization:'Bearer '+config.apiKey,'Content-Type':'application/json'},body:JSON.stringify(body),signal:AbortSignal.timeout(240000)});
  const raw=await response.json();
  if(!response.ok) throw Error('Grok HTTP '+response.status);
  fs.writeFileSync(new URL(`${prefix}-attempt-${calls}.json`,out),JSON.stringify(raw,null,2));
  return {ok:true,data:grokResponsesPublicResult(raw,built.resultOptions),providerCallCount:1};
});
fs.writeFileSync(new URL(prefix+'-backend-result.json',out),JSON.stringify(result,null,2));
const context={console};context.globalThis=context;
for(const name of ['h3-prompt-format.js','ai-sequence-minimax-h3-prompt.workflow.js','ai-sequence-minimax-h3-reverse.workflow.js']) vm.runInNewContext(fs.readFileSync(new URL('../particle-editor/'+name,import.meta.url),'utf8'),context);
const current={modelId:'minimax_h3_local',mode:payload.h3Mode,durationSeconds:payload.durationSeconds,prompt:payload.userPrompt,requirements:payload.userRequirements,contentPolicy:payload.contentPolicy,resources:payload.images.map(image=>({key:image.role,identity:image.role,occupied:true,kind:'image',fileName:image.name,mimeType:'image/png',dataUrl:image.dataUrl}))};
const workflow=context.NovaFlowAiSequenceMiniMaxH3ReverseWorkflow;
const prepared=workflow.prepareRequest(current);
const restored=workflow.validateAndRestore({text:result.data.output_text,context:prepared.context,current});
fs.writeFileSync(new URL(prefix+'-output.txt',out),restored.text);
fs.writeFileSync(new URL(prefix+'-result.json',out),JSON.stringify({ok:true,calls,elapsedMs:Date.now()-started,chars:restored.text.length},null,2));
console.log(JSON.stringify({ok:true,calls,elapsedMs:Date.now()-started,chars:restored.text.length}));
